#!/bin/bash
# =====================================================================
# 5つの時点(返答の終わり・補助役の終わり・会話の終わり・道具の呼び出しのあと・会話の始め)の hook:
# AIの作業の集計に要る記録を残す
#
# 標準入力をそのまま extract.pl hook に渡し、extract.pl の標準出力をそのまま返す。
# 入力の欄は読まない(Claude Code が形を決めている欄を読むのは extract.pl だけにする。
# 入力の形が変わっても、このファイルを直さずに済むようにするため)。
# extract.pl の場所は CLAUDE_PROJECT_DIR から作る(会話の途中で cd しても見つけられるように)。
# extract.pl が失敗しても 0 で終わる(会話を止めないため)。
# =====================================================================
perl "${CLAUDE_PROJECT_DIR}/.claude/scripts/usage/extract.pl" hook
exit 0
